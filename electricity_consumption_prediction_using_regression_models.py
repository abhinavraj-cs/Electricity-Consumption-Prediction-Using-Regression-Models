from sklearn.linear_model import Ridge
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

models = {
    'Linear Regression': model,
    'Ridge Regression': Ridge(alpha=1.0),
    'Random Forest': RandomForestRegressor(n_estimators=100, random_state=42, n_jobs=-1),
    'Gradient Boosting': GradientBoostingRegressor(n_estimators=100, random_state=42)
}

results = []
trained_models = {}

for name, regressor in models.items():
    if name != 'Linear Regression':
        regressor.fit(X_train, Y_train)

    y_pred_model = regressor.predict(X_test)
    trained_models[name] = regressor

    mae = mean_absolute_error(Y_test, y_pred_model)
    mse = mean_squared_error(Y_test, y_pred_model)
    rmse = np.sqrt(mse)
    r2 = r2_score(Y_test, y_pred_model)

    results.append({
        'Model': name,
        'MAE (kWh)': round(mae, 2),
        'MSE': round(mse, 2),
        'RMSE (kWh)': round(rmse, 2),
        'R2 Score': round(r2, 4)
    })

comparison_df = pd.DataFrame(results).sort_values(by='R2 Score', ascending=False).reset_index(drop=True)
display(comparison_df)

