def predict_household_consumption(house_details):
    input_df = pd.DataFrame([house_details])

    encoded_df = pd.get_dummies(
        input_df,
        columns=['House_Type', 'Season', 'EV_Charger', 'Solar_Panels'],
        drop_first=True
    )

    trained_cols = joblib.load('trained_feature_columns.pkl')
    for col in trained_cols:
        if col not in encoded_df.columns:
            encoded_df[col] = 0
    encoded_df = encoded_df[trained_cols]

    saved_scaler = joblib.load('scaler.pkl')
    encoded_df[numerical_cols] = saved_scaler.transform(encoded_df[numerical_cols])

    saved_model = joblib.load('electricity_best_model.pkl')
    prediction = saved_model.predict(encoded_df)[0]

    return round(prediction, 2)
